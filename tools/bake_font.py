#!/usr/bin/env python3
"""Bakes the clear-text font (DejaVu Sans Condensed Bold, free licence, see tools/fonts/DejaVu-LICENSE.txt)
into src/clearfont.h: ASCII 32..126, 8-bit anti-aliased alpha atlas. Usage: bake_font.py [size]"""
import sys
from PIL import Image, ImageDraw, ImageFont
size = int(sys.argv[1]) if len(sys.argv) > 1 else 20
font = ImageFont.truetype('tools/fonts/DejaVuSansCondensed-Bold.ttf', size)
asc, desc = font.getmetrics()
glyphs = []
AW = 256
x = y = rowh = 0
atlas = Image.new('L', (AW, 256), 0)
for c in range(32, 127):
    ch = chr(c)
    l, t, r, b = font.getbbox(ch, anchor='ls')
    w, h = max(r - l, 0), max(b - t, 0)
    adv = int(round(font.getlength(ch)))
    if w and h:
        if x + w + 1 > AW: x = 0; y += rowh + 1; rowh = 0
        im = Image.new('L', (w, h), 0)
        ImageDraw.Draw(im).text((-l, -t), ch, font=font, fill=255, anchor='ls')
        atlas.paste(im, (x, y))
        glyphs.append((x, y, w, h, l, t, adv)); x += w + 1; rowh = max(rowh, h)
    else:
        glyphs.append((0, 0, 0, 0, 0, 0, adv))
ah = y + rowh + 1
atlas = atlas.crop((0, 0, AW, ah))
data = atlas.tobytes()
with open('src/clearfont.h', 'w') as f:
    f.write('/* Generated by tools/bake_font.py from DejaVu Sans Condensed Bold (Bitstream Vera / DejaVu licence, tools/fonts/DejaVu-LICENSE.txt). */\n')
    f.write('#define CF_SIZE %d\n#define CF_ASCENT %d\n#define CF_LINE %d\n#define CF_AW %d\n#define CF_AH %d\n' % (size, asc, asc + desc, AW, ah))
    f.write('/* x, y, w, h, left bearing, top (relative to the baseline, negative = above), advance */\n')
    f.write('static const short cf_glyph[95][7] = {\n' + ',\n'.join('{%s}' % ','.join(map(str, g)) for g in glyphs) + '\n};\n')
    f.write('static const unsigned char cf_atlas[%d] = {\n' % len(data))
    for i in range(0, len(data), 32):
        f.write(','.join(str(v) for v in data[i:i+32]) + ',\n')
    f.write('};\n')
print('size', size, 'asc', asc, 'desc', desc, 'atlas', AW, 'x', ah, len(data), 'bytes')

#!/usr/bin/env python3
"""Writes src/lang_ids.h (enum of UI string ids + the English table) from ui_en.py, so the C code and the language packs agree."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from ui_en import UI, LANGS
out = ['/* Generated by tools/lang/gen_ids.py from tools/lang/ui_en.py - do not edit. */', 'enum {']
out += ['    L_%s,' % k for k, _ in UI] + ['    L_COUNT', '};']
out += ['static const char* const L_EN[L_COUNT] = {']
out += ['    "%s",' % v.replace('\\', '\\\\').replace('"', '\\"') for _, v in UI] + ['};']
out += ['#define N_LANGS %d' % len(LANGS), 'static const char* const LANG_CODES[N_LANGS] = { %s };' % ', '.join('"%s"' % c for c, _ in LANGS)]
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'src', 'lang_ids.h'), 'w').write('\n'.join(out) + '\n')
print('ok', len(UI), 'strings')

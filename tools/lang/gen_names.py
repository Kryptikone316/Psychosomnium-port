#!/usr/bin/env python3
"""Bakes the 12 language names (native script) into src/clearnames.h, so the Language row can always show every language in its own writing.
Latin/Cyrillic/Arabic: DejaVu Sans Condensed Bold; Japanese/Chinese names: Noto Sans CJK Bold (SIL OFL). Arabic is shaped and stored in visual order."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import build_packs as bp
from ui_en import LANGS
from PIL import ImageFont, Image, ImageDraw
SIZE = bp.SIZE
dv = ImageFont.truetype(*[bp.FONTS['default'][0]], SIZE)
cjk = {'ja': ImageFont.truetype(bp.FONTS['ja'][0], SIZE, index=0), 'zh': ImageFont.truetype(bp.FONTS['zh'][0], SIZE, index=2)}
names = []
for code, name in LANGS:
    s = bp.shape_ar(name) if code == 'ar' else name
    if code == 'ar': s = s[::-1]                                   # visual order (the whole name is right-to-left)
    names.append((code, s))
glyphs = {}; atlas = Image.new('L', (512, 256), 0); x = y = rowh = 0
for code, s in names:
    f = cjk.get(code, dv)
    for ch in s:
        key = (ord(ch), code if code in cjk else 'x')
        if key in glyphs: continue
        l, t, r, b = f.getbbox(ch, anchor='ls'); w, h = max(r - l, 0), max(b - t, 0); adv = int(round(f.getlength(ch)))
        if w and h:
            if x + w + 1 > 512: x = 0; y += rowh + 1; rowh = 0
            im = Image.new('L', (w, h), 0); ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255, anchor='ls')
            atlas.paste(im, (x, y)); glyphs[key] = (x, y, w, h, l, t, adv); x += w + 1; rowh = max(rowh, h)
        else: glyphs[key] = (0, 0, 0, 0, 0, 0, adv)
ah = y + rowh + 1; atlas = atlas.crop((0, 0, 512, ah)); data = atlas.tobytes()
keys = sorted(glyphs)
out = ['/* Generated by tools/lang/gen_names.py - the language names in their own scripts (fonts: DejaVu Sans, Noto Sans CJK; see licenses/). */',
       '#define NM_AW 512', '#define NM_AH %d' % ah, '#define NM_N %d' % len(keys), '/* codepoint, set (0 = general, 1 = ja, 2 = zh), x, y, w, h, left, top, advance */',
       'static const int nm_g[NM_N][9] = {']
for k in keys:
    g = glyphs[k]; st = {'x': 0, 'ja': 1, 'zh': 2}[k[1]]
    out.append('{%d,%d,%s},' % (k[0], st, ','.join(map(str, g))))
out.append('};')
out.append('static const unsigned short nm_text[%d][40] = {' % len(names))
for code, s in names:
    st = {'ja': 1, 'zh': 2}.get(code, 0)
    out.append('{%s,0},   /* %s */' % (','.join('%d' % ord(c) for c in s), code))
out.append('};')
out.append('static const unsigned char nm_set[%d] = { %s };' % (len(names), ','.join(str({'ja': 1, 'zh': 2}.get(c, 0)) for c, _ in names)))
out.append('static const unsigned char nm_atlas[%d] = {' % len(data))
for i in range(0, len(data), 40): out.append(','.join(str(v) for v in data[i:i + 40]) + ',')
out.append('};')
open(os.path.join(bp.ROOT, 'src', 'clearnames.h'), 'w').write('\n'.join(out) + '\n')
print('names header:', len(keys), 'glyphs, atlas', 512, 'x', ah)
